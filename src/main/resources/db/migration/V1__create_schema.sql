-- EventDesk schema.
-- Flyway owns the schema; Hibernate only validates it (spring.jpa.hibernate.ddl-auto=validate).

-- btree_gist lets a GiST index combine plain equality (venue_id =) with
-- range overlap (&&). The exclusion constraint on event_requests needs both.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE clubs (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE venues (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(150) NOT NULL,
    capacity INTEGER      NOT NULL CHECK (capacity > 0)
);

-- "user" is a reserved word in PostgreSQL, hence app_users.
CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CLUB', 'VENUE_OFFICE', 'DEAN')),
    club_id       BIGINT REFERENCES clubs (id),
    -- A club coordinator always belongs to a club; staff never do.
    CONSTRAINT club_role_has_club CHECK ((role = 'CLUB') = (club_id IS NOT NULL))
);

CREATE TABLE event_requests (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id             BIGINT        NOT NULL REFERENCES clubs (id),
    venue_id            BIGINT        NOT NULL REFERENCES venues (id),
    submitted_by        BIGINT        NOT NULL REFERENCES app_users (id),
    title               VARCHAR(150)  NOT NULL,
    description         VARCHAR(2000) NOT NULL,
    event_type          VARCHAR(20)   NOT NULL
        CHECK (event_type IN ('TECHNICAL', 'WORKSHOP', 'WEBINAR', 'CULTURAL', 'OTHER')),
    expected_attendance INTEGER       NOT NULL CHECK (expected_attendance > 0),
    starts_at           TIMESTAMPTZ   NOT NULL,
    ends_at             TIMESTAMPTZ   NOT NULL,
    status              VARCHAR(20)   NOT NULL
        CHECK (status IN ('PENDING_VENUE', 'PENDING_DEAN', 'APPROVED', 'REJECTED', 'CANCELLED')),
    rejection_reason    VARCHAR(500),
    created_at          TIMESTAMPTZ   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    version             BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT event_ends_after_start CHECK (ends_at > starts_at),

    -- The core guarantee: no two live requests may hold the same venue at
    -- overlapping times. '[)' makes the range half-open, so a 10:00-12:00
    -- booking and a 12:00-14:00 booking do NOT conflict.
    -- Rejected and cancelled requests are excluded, so they free the slot.
    -- Keep this status list in sync with RequestStatus.holdsVenue().
    CONSTRAINT no_overlapping_venue_bookings EXCLUDE USING gist (
        venue_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status IN ('PENDING_VENUE', 'PENDING_DEAN', 'APPROVED'))
);

CREATE INDEX idx_event_requests_club   ON event_requests (club_id);
CREATE INDEX idx_event_requests_status ON event_requests (status);

-- Append-only audit trail: who did what to which request, and when.
CREATE TABLE request_actions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_request_id BIGINT      NOT NULL REFERENCES event_requests (id),
    actor_id         BIGINT      NOT NULL REFERENCES app_users (id),
    action           VARCHAR(20) NOT NULL CHECK (action IN ('SUBMITTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    from_status      VARCHAR(20),
    to_status        VARCHAR(20) NOT NULL,
    remark           VARCHAR(500),
    created_at       TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_request_actions_request ON request_actions (event_request_id);
